esp_err_t bsp_lcd_init(esp_lcd_panel_io_handle_t *out_io,
                       esp_lcd_panel_handle_t *out_panel)
{
    if (out_io == NULL || out_panel == NULL) {
        return ESP_ERR_INVALID_ARG;
    }
    if (s_inited) {
        /* Idempotent: return existing handles so bsp_init() + lvgl_port_init()
         * (or any other duplicate caller) can both call us safely. */
        *out_io    = s_io;
        *out_panel = s_panel;
        return ESP_OK;
    }

    /* 1) Backlight off first to avoid white flash on power-up */
    gpio_config_t bk_cfg = {
        .mode = GPIO_MODE_OUTPUT,
        .pin_bit_mask = 1ULL << BSP_PIN_LCD_BK,
    };
    ESP_ERROR_CHECK(gpio_config(&bk_cfg));

    /* 2) SPI bus */
    ESP_LOGI(TAG, "Initialize SPI bus");
    const spi_bus_config_t buscfg = AXS15231B_PANEL_BUS_SPI_CONFIG(
        BSP_PIN_LCD_SCLK, BSP_PIN_LCD_MOSI,
        BSP_LCD_H_RES * BSP_LCD_DRAW_BUFF_HEIGHT * sizeof(uint16_t));
    ESP_ERROR_CHECK(spi_bus_initialize(BSP_LCD_SPI_NUM, &buscfg, SPI_DMA_CH_AUTO));

    /* 3) Panel IO */
    ESP_LOGI(TAG, "Install panel IO");
    const esp_lcd_panel_io_spi_config_t io_config = {
        .dc_gpio_num = BSP_PIN_LCD_DC,
        .cs_gpio_num = BSP_PIN_LCD_CS,
        .pclk_hz    = BSP_LCD_PIXEL_CLK_HZ,
        .lcd_cmd_bits  = 8,
        .lcd_param_bits = 8,
        .spi_mode   = 0,
        .trans_queue_depth = 10,
    };
    ESP_ERROR_CHECK(esp_lcd_new_panel_io_spi(BSP_LCD_SPI_NUM, &io_config, &s_io));

    /* 4) AXS15231B panel driver + init sequence */
    axs15231b_vendor_config_t vendor_config = {
        .init_cmds = lcd_init_cmds,
        .init_cmds_size = sizeof(lcd_init_cmds) / sizeof(axs15231b_lcd_init_cmd_t),
        .flags = { .use_qspi_interface = 0 },
    };
    esp_lcd_panel_dev_config_t panel_config = {
        .reset_gpio_num = BSP_PIN_LCD_RST,
        .rgb_ele_order  = LCD_RGB_ELEMENT_ORDER_RGB,
        .bits_per_pixel = BSP_LCD_COLOR_DEPTH,
        .vendor_config  = &vendor_config,
    };
    ESP_LOGI(TAG, "Install AXS15231B panel driver");
    ESP_ERROR_CHECK(esp_lcd_new_panel_axs15231b(s_io, &panel_config, &s_panel));

    ESP_ERROR_CHECK(esp_lcd_panel_reset(s_panel));
    ESP_ERROR_CHECK(esp_lcd_panel_init(s_panel));
    ESP_ERROR_CHECK(esp_lcd_panel_disp_on_off(s_panel, false));

    /* 5) Backlight on */
    ESP_LOGI(TAG, "Turn on LCD backlight");
    gpio_set_level(BSP_PIN_LCD_BK, BSP_LCD_BK_ON_LEVEL);

    *out_io    = s_io;
    *out_panel = s_panel;
    s_inited = true;
    return ESP_OK;
}

esp_err_t bsp_lcd_set_backlight(bool on)
{
    if (!s_inited) {
        return ESP_ERR_INVALID_STATE;
    }
    gpio_set_level(BSP_PIN_LCD_BK, on ? BSP_LCD_BK_ON_LEVEL : BSP_LCD_BK_OFF_LEVEL);
    return ESP_OK;
}

esp_err_t bsp_lcd_deinit(void)
{
    if (!s_inited) {
        return ESP_ERR_INVALID_STATE;
    }
    /* Order: panel → panel_io → SPI bus; backlight stays as-is (GPIO persists) */
    if (s_panel) {
        esp_lcd_panel_del(s_panel);
        s_panel = NULL;
    }
    if (s_io) {
        esp_lcd_panel_io_del(s_io);
        s_io = NULL;
    }
    spi_bus_free(BSP_LCD_SPI_NUM);
    s_inited = false;
    return ESP_OK;
}